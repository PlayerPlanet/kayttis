"""Generate poster-05-tarina.html: short timeline + branching tree of decisions.
Edit FORKS below and run:  python3 build_tarina.py
Page coordinates are millimetres on the A2 sheet (420 x 594)."""
from pathlib import Path

PHASES = ["Idea", "Pilottitesti", "Käyttäjätesti", "Loppudemo"]
PHASE_SUB = ["", "", "", ""]

ROOT = ("Idea", "Tiskikoneen hana jäi auki.")
# (phase, question, chosen, why, rejected)
FORKS = [
    ("Idea", "Mitä rakennetaan?", "Kaikkien laitteiden tila", "Ihmisiä kiinnosti moni muukin laite: liesi, valot, kahvinkeitin.", "Laite, joka kääntää tiskikoneen hanan kiinni"),
    ("RT7", "Kenelle?", "Asunnonomistajat omakotitaloissa", "Isossa talossa on enemmän laitteita ja enemmän tarkistettavaa.", "Opiskelijat pienissä asunnoissa"),
    ("RT8", "Missä tila näkyy?", "Sovellus puhelimeen", "Kotia haluttiin seurata myös kotoa lähdettyä.", "Ohjauspaneeli eteisessä"),
    ("RT8", "Miten laitteet liitetään?", "Yksi sensori kaikille", "Toimii ilman älylaitteita, eikä vaadi uutta sovellusta jokaiselle.", "Integraatio jokaiseen älylaitteeseen"),
    ("RT8", "Lista vai pohjapiirros?", "Lista", "Lista on helppo ottaa käyttöön. Pohjapiirros piti ensin piirtää.", "Pohjapiirros"),
    ("RT8", "Voiko laitteita sulkea?", "Vain seuranta", "Päälle kytkemistä vastustettiin. Seuranta pysyy yksinkertaisena.", "Etäsulku omilla sulkimilla"),
]
END = ("Loppudemo", "Hanax tänään.", "Yksi sensori, yksi lista, puhelimessa.")

TRUNK = 150          # x of the trunk
REJ_R = 122          # rejected labels end (right-aligned) here
TEXT_L = 166         # chosen text starts here
Y0, Y_END = 214, 550  # root node, end node
step = (Y_END - Y0) / (len(FORKS) + 1)

svg, html = [], []
ys = [Y0 + step * (i + 1) for i in range(len(FORKS))]
svg.append(f'<path d="M{TRUNK} {Y0}V{Y_END}" class="trunk"/>')
# root
svg.append(f'<circle cx="{TRUNK}" cy="{Y0}" r="3.2" class="hollow"/>')
html.append(f'<div class="node" style="top:{Y0-5.4:.1f}mm"><b>{ROOT[1]}</b></div>')
for (ph, q, ch, why, rej), y in zip(FORKS, ys):
    by = y + 15
    svg.append(f'<path d="M{TRUNK} {y:.1f}C{TRUNK} {by-4:.1f} {TRUNK-6} {by:.1f} {TRUNK-16} {by:.1f}H{REJ_R+4}" class="rej"/>')
    svg.append(f'<path d="M{REJ_R+1.6} {by-2.4:.1f}l4.8 4.8m0 -4.8l-4.8 4.8" class="x"/>')
    svg.append(f'<circle cx="{TRUNK}" cy="{y:.1f}" r="2.4" class="dot"/>')
    html.append(f'<div class="node" style="top:{y-5.4:.1f}mm"><b>{ch}</b><p>{why}</p></div>')
    html.append(f'<div class="rejl" style="top:{by-4.4:.1f}mm">{rej}</div>')
svg.append(f'<circle cx="{TRUNK}" cy="{Y_END}" r="5" class="end"/><circle cx="{TRUNK}" cy="{Y_END}" r="2.4" class="dot"/>')
html.append(f'<div class="node end" style="top:{Y_END-6.4:.1f}mm"><b>{END[1]}</b><p>{END[2]}</p></div>')

# short timeline (top right): four stops
TL_L, TL_R, TL_Y = 16, 404, 160
tl_svg = [f'<path d="M{TL_L} {TL_Y}H{TL_R}" class="trunk"/>']
tl_html = []
for i, (p, sub) in enumerate(zip(PHASES, PHASE_SUB)):
    x = TL_L + (TL_R - TL_L) * i / (len(PHASES) - 1)
    tl_svg.append(f'<circle cx="{x:.1f}" cy="{TL_Y}" r="3" class="dot"/>')
    align = "left" if i == 0 else ("right" if i == len(PHASES) - 1 else "center")
    shift = "0" if i == 0 else ("-100%" if i == len(PHASES) - 1 else "-50%")
    tl_html.append(f'<div class="tl" style="left:{x:.1f}mm; top:{TL_Y+6}mm; text-align:{align}; transform:translateX({shift})"><b>{p}</b></div>')

page = f'''<!doctype html>
<html lang="fi">
<head>
<meta charset="utf-8">
<title>Hanax – juliste 5: meidän tarina</title>
<script src="../../src/theme.js"></script>
<link rel="stylesheet" href="../../src/hanax-print.css">
<link rel="stylesheet" href="../../src/poster.css">
<link rel="stylesheet" href="final.css">
<style>
  /* generated by build_tarina.py */
  .tree {{ position: absolute; left: 0; top: 0; width: 420mm; height: 594mm; overflow: visible; }}
  .tree .trunk {{ stroke: var(--ink); stroke-width: 0.6; fill: none; }}
  .tree .rej {{ stroke: var(--muted); stroke-width: 0.5; stroke-dasharray: 1.8 1.4; fill: none; }}
  .tree .x {{ stroke: var(--muted); stroke-width: 0.7; fill: none; }}
  .tree .dot {{ fill: var(--ink); }}
  .tree .hollow, .tree .end {{ fill: var(--bg); stroke: var(--ink); stroke-width: 0.6; }}
  .node {{ position: absolute; left: {TEXT_L}mm; right: 16mm; }}
  .node .k {{ font-size: 3.8mm; }}
  .node b {{ display: block; font-weight: 600; font-size: 11mm; letter-spacing: -0.03em; line-height: 1.05; margin-top: 0; }}
  .node p {{ font-size: 7mm; color: var(--muted); letter-spacing: -0.01em; margin-top: 1.6mm; }}
  .node.end b {{ font-size: 13mm; }}
  .rejl {{ position: absolute; right: {420-REJ_R+3}mm; width: {REJ_R-19}mm; text-align: right; font-size: 7mm; line-height: 1.15; color: var(--muted); letter-spacing: -0.01em; }}
  .tl {{ position: absolute; white-space: nowrap; }}
  .tl b {{ display: block; font-weight: 600; font-size: 8mm; letter-spacing: -0.02em; }}
  .tl .k {{ font-size: 3.8mm; margin-top: 1.4mm; }}
  .legend {{ left: 236mm; top: 124mm; display: flex; gap: 10mm; font-size: 5.6mm; color: var(--muted); }}
  .legend span {{ display: inline-flex; align-items: center; gap: 3mm; }}
  .legend i {{ display: inline-block; width: 12mm; border-top: 0.6mm solid var(--ink); }}
  .legend i.d {{ border-top: 0.5mm dashed var(--line-strong); }}
</style>
</head>
<body>
<div class="page">
  <div class="grid" style="--cell:20mm; --gx:16mm; --gy:6mm; --gmask: 60% 20% at 50% 10%"></div>
  <header class="hdr">
    <span><img class="logo-d" src="../../../../brand/logo/hanax-lockup-on-dark.svg" alt="Hanax"><img class="logo-l" src="../../../../brand/logo/hanax-lockup.svg" alt="Hanax"></span>
  </header>
  <h1 class="abs h claim">Meidän<br>tarina.</h1>

  <svg class="tree" viewBox="0 0 420 594" aria-hidden="true">
    {"".join(tl_svg)}
    {"".join(svg)}
  </svg>
  {"".join(tl_html)}
  <div class="abs legend"><span><i></i>Valitsimme</span><span><i class="d"></i>Hylkäsimme</span></div>
  {"".join(html)}
</div>
</body>
</html>
'''
Path(__file__).with_name("poster-05-tarina.html").write_text(page, encoding="utf-8")
print("wrote poster-05-tarina.html")
